import { readdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { createHash } from 'node:crypto';
async function files(root, directory) {
  return (
    await Promise.all(
      (await readdir(path.join(root, directory), { withFileTypes: true })).map((entry) =>
        entry.isDirectory()
          ? files(root, `${directory}/${entry.name}`)
          : `${directory}/${entry.name}`,
      ),
    )
  ).flat();
}
/** Cache the shipped application tree, never a vault, profile, or test fixture. */
export async function writeOfflineShell(root) {
  const paths = [
    'index.html',
    'pdf.html',
    'manifest.webmanifest',
    ...(await files(root, 'src')),
    ...(await files(root, 'public')),
  ].sort();
  const hash = createHash('sha256');
  for (const file of paths) {
    hash.update(file);
    hash.update(await readFile(path.join(root, file)));
  }
  const version = hash.digest('hex').slice(0, 16);
  const shell = ['./', ...paths.map((file) => './' + file)];
  const source = `// Generated by scripts/offline.mjs from the shipped source and assets.\nconst CACHE='ivo-shell-${version}';\nconst SHELL=${JSON.stringify(shell)};\n
self.addEventListener('install',event=>event.waitUntil(caches.open(CACHE).then(cache=>cache.addAll(SHELL))));
self.addEventListener('activate',event=>event.waitUntil(caches.keys().then(keys=>Promise.all(keys.filter(key=>key.startsWith('ivo-shell-')&&key!==CACHE).map(key=>caches.delete(key)))).then(()=>self.clients.claim())));
self.addEventListener('fetch',event=>{
 if(event.request.method!=='GET')return;
 const url=new URL(event.request.url);
 if(url.origin!==self.location.origin)return;
 if(!SHELL.some(file=>new URL(file,self.registration.scope).href===url.href))return;
 event.respondWith(fetch(event.request).then(response=>{
  if(response.ok){const copy=response.clone();event.waitUntil(caches.open(CACHE).then(cache=>cache.put(event.request,copy)));}
  return response;
 }).catch(()=>caches.match(event.request).then(hit=>hit||Response.error())));
});\n`;
  await writeFile(path.join(root, 'sw.js'), source);
  return { version, files: paths.length };
}
